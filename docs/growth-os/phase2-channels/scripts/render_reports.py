# ---------------- 05 CAC and LTV ----------------
def r05():
    L = ['# 05 CAC and LTV Model', '', HEAD, '',
         '**Every number here is a scenario.** Built2Bid had 0 paying accounts at the 2026-11-16 baseline [P1:E190], so there is no observed CAC, conversion, retention or plan mix [G207].', '',
         '## Baseline assumptions', '',
         '| Id | Assumption | Optimistic | Base | Conservative | Needs experiment | Basis |', '|---|---|---|---|---|---|---|']
    for a in AS.values():
        if 'by_unit' in a:
            for u, v in a['by_unit'].items():
                if isinstance(v, dict):
                    if v['base'] is None:
                        continue
                    L.append(f"| {a['id']} | {a['name']} ({u}) | {v['optimistic']} | {v['base']} | {v['conservative']} | {'yes ' + a['experiment'] if a['requires_experiment'] else 'no'} | [{a['id']}] |")
                else:
                    L.append(f"| {a['id']} | {a['name']} ({u}) | | {v} | | {'yes ' + a['experiment'] if a['requires_experiment'] else 'no'} | [{a['id']}] |")
        else:
            v = a['value']
            if isinstance(v, dict) and 'base' in v:
                L.append(f"| {a['id']} | {a['name']} | {v['optimistic']} | {v['base']} | {v['conservative']} | {'yes ' + a['experiment'] if a['requires_experiment'] else 'no'} | [{a['id']}] |")
            else:
                L.append(f"| {a['id']} | {a['name']} | | {json.dumps(v)} | | {'yes ' + a['experiment'] if a['requires_experiment'] else 'no'} | [{a['id']}] |")
    L += ['', 'Basis for each assumption (benchmarks are anchors from other businesses, not contractor statistics):', '']
    for a in AS.values():
        L.append(f"- **{a['id']} {a['name']}:** {a['basis']}")
    L += ['', '## Unit economics per paying account [M]', '',
          '| Scenario | ARPA | Net of card fees | Contribution margin | Gross profit / month | Monthly churn | Expected paid months (capped) | LTV (gross profit) | Max CAC for 10-month payback |', '|---|---|---|---|---|---|---|---|---|']
    for s in SC:
        x = LTV[s]
        L.append(f"| {s} | ${x['arpa_usd_month']} | ${x['net_revenue_usd_month']} | {x['contribution_margin_pct']}% | ${x['gross_profit_usd_month']} | {x['monthly_churn_pct']}% | {x['expected_paid_months_capped']} | {money(x['ltv_gross_profit_usd'])} | {money(x['max_cac_for_payback_usd'])} | [F07] [F08] [F09] [F10] [F11] [M]")
    L += ['', 'ARPA blends the Phase 1 solo and employer ARPA, which come from real list prices ($19.99/month, $199/year, Enterprise $49.99/month) and an assumed plan mix [P1:E180] [P1:E181] [P1:E182], weighted by the employer share [F08].', '',
          '## CAC by channel [M]', '',
          '| Buy unit | Scenario | CPC | Landing conv. | 7-day activation | Activated to paid | Click to paid | Cost per signup | Cost per activated | CAC |', '|---|---|---|---|---|---|---|---|---|---|']
    for (u, s), r in sorted(UE.items()):
        L.append(f"| {u} | {s} | ${float(r['cpc_usd']):.2f} | {r['landing_conversion_pct']}% | {r['activation_7d_pct']}% | {r['activated_to_paid_pct']}% | {r['click_to_paid_pct']}% | {money(r['cost_per_signup_usd'])} | {money(r['cost_per_activated_usd'])} | {money(r['cac_usd'])} | [F01] [F03] [F04] [F05] [F06] [M]")
    L += ['', 'Conservative rows multiply four pessimistic rates, so CAC above $10,000 means "no realistic payback", not a precise figure [M].', '',
          '## Break-even: what has to be true [M]', '',
          'The maximum CAC for a 10-month gross-profit payback (the ADS.md threshold) is set against each channel\'s base CPC. The last column says how many times better than base the click-to-paid rate must be.', '',
          '| Buy unit | Base CPC | Max CAC | Required click to paid | Base click to paid | Improvement needed |', '|---|---|---|---|---|---|']
    for r in BE:
        L.append(f"| {r['unit']} | ${float(r['base_cpc_usd']):.2f} | {money(r['max_cac_usd_10mo_payback'])} | {r['required_click_to_paid_pct']}% | {r['base_click_to_paid_pct']}% | {r['improvement_multiple_needed']}x | [F01] [F06] [M]")
    L += ['', '## What this means', '',
          '- At $19.99/month, paid acquisition only works if the funnel performs far better than the base case, or if more accounts buy annual, Enterprise or add-ons [M] [F08].',
          '- The cheapest lever is not ad spend. Activation [F04] and activated-to-paid [F06] multiply every channel at once, so onboarding and lifecycle work (Phase 8) moves CAC more than channel choice [INF].',
          '- Meta and partner channels need a smaller improvement multiple than search because their clicks are cheaper; search needs fewer clicks per customer. Only the experiments can settle which wins [X05] [X06] [X08].', '']
    w('05_cac_ltv_model.md', L)


# ---------------- 06 Experiment plan ----------------
def r06():
    L = ['# 06 30/60/90-Day Experiment Plan', '', HEAD, '',
         'Free experiments come first. No paid experiment starts until the measurement gate passes for that channel and the owner signs the ADS.md approval table.', '']
    for win in ['Days 1-30', 'Days 15-90', 'Days 31-60', 'Days 31-90', 'Days 61-90', 'Days 1-90', 'Day 90+']:
        xs = [x for x in EX if x['window'] == win]
        if not xs:
            continue
        L += [f'## {win}', '']
        for x in xs:
            cost = x['cost_usd'] if isinstance(x['cost_usd'], str) else f"${x['cost_usd']}"
            L += [f"### [{x['id']}] {x['name']} ({x['channel']})", '',
                  f"- **Hypothesis:** {x['hypothesis']}",
                  f"- **Actions:** {x['actions']}",
                  f"- **Metric:** {x['metric']}",
                  f"- **Replaces:** {', '.join(x['replaces'])}",
                  f"- **Sample:** {x['sample']}",
                  f"- **Decision rule:** {x['decision']} [PARAM]",
                  f"- **Cost:** {cost}; owner action needed: {'yes' if x['needs_owner'] else 'no'} [PARAM]", '']
    L += ['## Assumptions that require experiments', '', '| Assumption | Experiment |', '|---|---|']
    for a in AS.values():
        if a['requires_experiment']:
            L.append(f"| [{a['id']}] {a['name']} | {a['experiment']} |")
    L += ['', '## Gaps register', '', '| Id | Gap | Resolution |', '|---|---|---|']
    for g in GAPS:
        L.append(f"| [{g['id']}] | {g['gap']} | {g['proposed_resolution']} |")
    w('06_experiment_plan.md', L)


