"""Render reports 01-06 from data/ and data/derived/. Deterministic; no network.

Run after build.py:  python3 scripts/render_reports.py
Tags: [CE###] Phase 2 evidence, [P1:E###] Phase 1 evidence, [C##]/[P1:S##] sources,
[F##] scenario assumption, [G2##] gap, [X##] experiment, [M] model output, [PARAM] analyst parameter,
[INF] analyst inference.
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *p: os.path.join(ROOT, *p)
rd = lambda p: list(csv.DictReader(open(P(p))))
CH = json.load(open(P('data/channels.json')))['channels']
CHD = {c['id']: c for c in CH}
AS = {a['id']: a for a in json.load(open(P('data/assumptions.json')))['assumptions']}
RU = json.load(open(P('data/model_rules.json')))
EX = json.load(open(P('data/experiments.json')))['experiments']
MAT = rd('data/derived/channel_opportunity_matrix.csv')
UE = {(r['unit'], r['scenario']): r for r in rd('data/derived/unit_economics.csv')}
BE = rd('data/derived/breakeven.csv')
LTV = json.load(open(P('data/derived/ltv.json')))
BS = json.load(open(P('data/derived/budget_scenarios.json')))['scenarios']
ORG = rd('data/derived/organic_allocation.csv')
GAPS = rd('data/gaps.csv')
SC = ['optimistic', 'base', 'conservative']
UNIT_NAME = {'SEARCH': 'Google Search ads', 'META': 'Meta (Facebook + Instagram placements)', 'YOUTUBE': 'YouTube ads',
             'PARTNERS': 'Creator partner pilot', 'LINKEDIN': 'LinkedIn ads', 'TIKTOK': 'TikTok ads'}
UNIT_EXP = {'SEARCH': 'X05', 'META': 'X06', 'YOUTUBE': 'X06', 'PARTNERS': 'X08'}
HEAD = 'Built2Bid Growth OS · Phase 2 · model v2.0.0 (2026-11-23) · generated by scripts/render_reports.py, do not edit by hand.'
DIMS = list(RU['weights'])
DN = {'audience_quality': 'Audience quality', 'purchase_intent': 'Purchase intent', 'expected_cac': 'Expected CAC',
      'content_cost': 'Content cost', 'measurability': 'Measurability', 'competitive_pressure': 'Competitive pressure',
      'evidence_confidence': 'Evidence confidence'}


def money(x):
    x = float(x)
    if x >= 10000:
        return '>$10,000'
    return f'${x:,.0f}' if x >= 100 else f'${x:,.2f}'


def tags(refs):
    return ' '.join(f'[{r}]' for r in refs)


def w(name, lines):
    open(P('reports', name), 'w').write('\n'.join(lines).rstrip() + '\n')


# ---------------- 01 Channel Opportunity Matrix ----------------
def r01():
    L = ['# 01 Channel Opportunity Matrix', '', HEAD, '',
         'Each channel is scored 1 to 5 on seven weighted dimensions [PARAM]. Weights: ' +
         ', '.join(f"{DN[d]} {int(RU['weights'][d] * 100)}%" for d in DIMS) + ' [PARAM].',
         'Expected CAC is computed for paid channels from the funnel assumptions [F01] [F03] [F04] [F05] [F06] against base LTV [M]; for owned and organic channels it is judgment.',
         'Adoption is never used as a weight. A platform with the most users can still score low if its users are not contractor owners with an estimating need [INF].', '',
         '## Scores and ranking [M]', '',
         '| Rank | Channel | ' + ' | '.join(DN[d] for d in DIMS) + ' | Score | Paid gate |',
         '|' + '---|' * (len(DIMS) + 4)]
    for r in MAT:
        L.append(f"| {r['rank']} | {r['channel']} | " + ' | '.join(r[d] for d in DIMS) + f" | **{r['opportunity_score']}** | {r['paid_gate_reason']} |")
    g = RU['paid_gates']
    L += ['', '## Paid-spend gates [PARAM]', '',
          f"- A channel can receive paid budget only if measurability is at least {g['min_measurability']} and the weighted score is at least {g['min_opportunity_score']} [PARAM].",
          f"- Below ${g['exploratory_from_budget']:,}/month, paid tests go only to channels with evidence confidence of at least {g['min_evidence_confidence']}. From ${g['exploratory_from_budget']:,} one exploratory channel (evidence {g['exploratory_min_evidence_confidence']}) may get its minimum viable test, and no more [PARAM].",
          '- A channel that fails the gates gets $0 paid spend and can still get organic time (report 04) [PARAM].', '',
          '## Score basis by channel', '']
    for c in CH:
        L += [f"### {c['name']}", '']
        L.append('| Dimension | Score | Basis |')
        L.append('|---|---|---|')
        row = next(r for r in MAT if r['channel_id'] == c['id'])
        for d in DIMS:
            s, basis, refs = c['scores'][d]
            if s is None:
                basis = f"{row['expected_cac_basis']} [M]"
                s = row['expected_cac']
            L.append(f"| {DN[d]} | {s} | {basis} {tags([x for x in refs if x not in basis])} |".replace('  ', ' '))
        L.append('')
    w('01_channel_opportunity_matrix.md', L)


