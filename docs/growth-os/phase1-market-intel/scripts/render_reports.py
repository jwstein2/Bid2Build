#!/usr/bin/env python3
"""Render the table-heavy reports from data/ so numbers are never hand-typed.
Writes reports/02-05. Deterministic; no network or AI calls.
Tags in brackets let tests/test_phase1.py check every number:
  [E###]  evidence row        [D###] audience frame row
  [T:SEG.field] segment_sizing / priority matrix   [M:scenario.field] model totals
  [A##] scenario assumption  [S##] source  [G##] gap
"""
import csv, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *p: os.path.join(ROOT, *p)

def rd(path):
    return list(csv.DictReader(open(P(path))))

def fmt(v):
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    if f.is_integer():
        return f"{int(f):,}"
    return f"{f:,}"

def tagify(text):
    return re.sub(r'(?<![\[\w:])([ED]\d{3})\b', r'[\1]', text)

def w(name, text):
    open(P('reports', name), 'w').write(text)

sources = json.load(open(P('data/sources.json')))
evidence = rd('data/evidence.csv')
A = json.load(open(P('data/assumptions.json')))
sizing = {r['segment_id']: r for r in rd('data/derived/segment_sizing.csv')}
matrix = rd('data/derived/trade_priority_matrix.csv')
model = json.load(open(P('data/derived/market_model_v1.json')))
mseg = rd('data/derived/market_model_v1_segments.csv')
personas = json.load(open(P('data/personas.json')))
segdef = json.load(open(P('data/segments.json')))

# ---------------- 02 Trade Priority Matrix ----------------
L = ["# Trade Priority Matrix (v1.0.0)", "",
     "Generated by `scripts/render_reports.py` from `data/derived/trade_priority_matrix.csv` and `data/derived/segment_sizing.csv`. Do not edit by hand.", "",
     "**How to read it.** Each trade is scored 1 to 5 on seven dimensions (weights in parentheses). D1 and D4 are computed from Census data. D2, D3, D5, D6 and D7 are analyst judgments; where a verified statistic informed the judgment, its evidence id is in the basis column of the CSV. Scores are a prioritization aid, not measurements. `Score ex-size` drops audience size and re-weights, which shows where smaller trades have strong per-account fit.", "",
     "Dimensions: D1 audience size (20%), D2 estimate intensity (20%), D3 job-complexity fit (15%), D4 owner purchase authority (10%), D5 software readiness (15%), D6 digital reachability (10%), D7 competitive whitespace (10%). Tiers: P1 >= 3.75, P2 3.20-3.74, P3 < 3.20. [PARAM: analyst-set weights in data/segments.json]", "",
     "Audience = business units with 1-20 total people including the owner: employer establishments with <20 paid employees [A02] plus nonemployers with receipts >= $25,000 (base floor) [A01]. Counts of workers are never used as audience.", "",
     "| Rank | Segment | 1-20 person units (base) | D1 | D2 | D3 | D4 | D5 | D6 | D7 | Score | Score ex-size | Tier | Confidence |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in matrix:
    u = r['units_1to20_base']
    units = f"{fmt(u)} [T:{r['segment_id']}.units_1to20_base]" if u else "not countable [G06]"
    L.append(f"| {r['rank']} | {r['segment']} | {units} | {r['D1']} | {r['D2']} | {r['D3']} | {r['D4']} | {r['D5']} | {r['D6']} | {r['D7']} | {r['weighted_score']} | {r['score_excluding_size']} | {r['tier']} | {r['score_confidence']} |")
L += ["", "## Segment size detail (owner-level units, not workers)", "",
      "| Segment | NAICS | Employer estabs (all sizes) | Employer estabs <20 paid employees | % <20 | Solo (all receipts, est.) | Solo viable low / base / high | 1-20 units low / base / high | Solo count method |",
      "|---|---|---|---|---|---|---|---|---|"]
for sid, z in sizing.items():
    if not z['employer_estab_total']:
        L.append(f"| {z['segment']} | none | n/a | n/a | n/a | n/a | n/a | n/a | {z['method_note']} [G06] |"); continue
    method = 'NES direct' if float(z['alloc_share']) == 1.0 else f"ESTIMATE: NES {z['nes_parent']} x {z['alloc_share']} [A03]"
    L.append(f"| {z['segment']} | {z['naics']} | {fmt(z['employer_estab_total'])} [T:{sid}.employer_estab_total] | {fmt(z['employer_estab_lt20'])} [T:{sid}.employer_estab_lt20] | {z['pct_employer_lt20']} [T:{sid}.pct_employer_lt20] | {fmt(z['solo_all_est'])} [T:{sid}.solo_all_est] | {fmt(z['solo_viable_low'])} / {fmt(z['solo_viable_base'])} / {fmt(z['solo_viable_high'])} [T:{sid}.solo_viable_low] [T:{sid}.solo_viable_base] [T:{sid}.solo_viable_high] | {fmt(z['units_1to20_low'])} / {fmt(z['units_1to20_base'])} / {fmt(z['units_1to20_high'])} [T:{sid}.units_1to20_low] [T:{sid}.units_1to20_base] [T:{sid}.units_1to20_high] | {method} |")
L += ["", "Shared codes: Plumbing and HVAC are both NAICS 238220; pressure and soft washing are both NAICS 561790. Each shared count appears twice above for reference but is counted once in the market model [G06].", "",
      "## Score basis by segment", ""]
for r in matrix:
    L.append(tagify(f"**{r['segment']}** ({r['tier']}): " + "; ".join(f"{k} {r[k]} = {r[k + '_basis']}" for k in ['D2', 'D3', 'D5', 'D6', 'D7'])))
    L.append("")
w('02_trade_priority_matrix.md', "\n".join(L))

# ---------------- 03 Evidence & Source Registry ----------------
L = ["# Evidence and Source Registry (v1.0.0)", "",
     "Generated from `data/sources.json` and `data/evidence.csv`. Every statistic used anywhere in Phase 1 has a row here with its source, base population, period and confidence. Machine-readable versions are the JSON and CSV files themselves.", "",
     "## Confidence scale", ""]
for k, v in sources['confidence_scale'].items():
    L.append(f"- **{k}**: {v}")
L += ["", "## Sources (requested starting points first)", ""]
for s in sources['sources']:
    L += [f"### {s['id']} {s['title']}", "",
          f"- Requested as: {s['requested_name']}",
          f"- Verification status: **{s['verification_status']}**",
          f"- Publisher: {s['publisher']}" + (f"; authors: {s['authors']}" if s.get('authors') else ''),
          f"- Release date: {s['release_date']}",
          f"- Data period: {s['data_period']}",
          f"- Sample / universe: {s['sample_definition']}",
          f"- Method: {s['methodology']}",
          f"- How verified: {s['how_verified']}",
          f"- Confidence: **{s['confidence']}**",
          f"- Limitations: {s['limitations']}",
          "- URLs: " + " ; ".join(s['urls']), ""]
L += ["## Evidence table", "", "| ID | Source | Metric | Value | Unit | Base | Period | Confidence | Note |", "|---|---|---|---|---|---|---|---|---|"]
for e in evidence:
    L.append(f"| {e['id']} | {e['source_id']} | {e['metric']} | {fmt(e['value'])} [{e['id']}] | {e['unit']} | {e['base_or_population']} | {e['period']} | {e['confidence']} | {e['note']} |")
w('03_evidence_and_source_registry.md', "\n".join(L) + "\n")

# ---------------- 04 Persona database ----------------
L = ["# Buyer Persona Database (v1.0.0)", "", "Generated from `data/personas.json`.", ""] + [f"> {n}" for n in personas['notes']] + ["", "## Built2Bid plans (real list prices from the app repository)", ""]
for k, v in personas['plans_real'].items():
    L.append(f"- **{k}**: {v}")
L.append("")
for p in personas['personas']:
    ref = p['audience_size_reference']
    L += [f"## {p['id']} {p['name']}", "",
          f"- Segments: {', '.join(p['segments'])}",
          f"- Audience reference: {fmt(ref['value'])} business units ({ref['metric']}; {ref['label']}; {ref['source']}) [T:persona.{p['id']}]",
          f"- Product tier: **{p['appropriate_product_tier']}**",
          f"- Confidence: {p['confidence']}", "", "**Company characteristics**", ""]
    for k, v in p['company_characteristics'].items():
        if k != 'evidence':
            L.append(tagify(f"- {k.replace('_', ' ')}: {v}") + (' [INF]' if k in ('total_people_incl_owner',) else ''))
    L.append(f"- evidence ids: {', '.join(p['company_characteristics']['evidence'])}")
    for sec, title in [('primary_business_problems', 'Primary business problems'), ('likely_software_objections', 'Likely software objections'), ('purchase_motivations', 'Purchase motivations'), ('channels', 'Channels')]:
        L += ["", f"**{title}**", ""]
        for x in p[sec].get('evidence', []):
            L.append(tagify(f"- Evidence: {x}"))
        for x in p[sec].get('inference', []):
            L.append(f"- Inference: {x} [INF]")
    for sec, title in [('best_built2bid_use_cases', 'Best Built2Bid use cases (inference)'), ('expected_buyer_journey', 'Expected buyer journey (inference)'), ('preferred_marketing_messages', 'Preferred marketing messages (hypotheses to test; follow Built2Bid ad rules; nothing has been launched)')]:
        L += ["", f"**{title}**", ""] + [f"- {x} [INF]" for x in p[sec]]
    L.append("")
w('04_buyer_persona_database.md', "\n".join(L))

# ---------------- 05 Market model ----------------
t = model['totals']
asm = {a['id']: a for a in A['assumptions']}
L = [f"# Addressable Market Scenario Model (v{model['model_version']})", "",
     f"Generated from `data/derived/market_model_v1.json` (model date {model['model_date']}). Unit: {model['unit']}.", "",
     f"> {model['label']}", "",
     "## Definitions", "",
     "- **TAM (units)**: U.S. business units with 1-20 total people including the owner, in residential and light-commercial building trades plus exterior cleaning [A08]. Employer part = CBP 2023 establishments with <20 paid employees [A02]. Solo part = NES 2024 nonemployers above a receipts floor that varies by scenario [A01]; 6-digit trade solo counts are allocated estimates [A03].",
     "- **SAM (units)**: TAM x segment fit weight from the Trade Priority Matrix tier [A04] x share likely to pay for estimating software [A05]. This is the step that stops the model from treating every construction business as a software buyer.",
     "- **SOM (accounts)**: SAM x obtainable share within 36 months [A06].",
     "- **Dollar values**: units x ARPA x 12. ARPA uses Built2Bid's real list prices with an assumed plan mix [A07]; free-plan users are excluded [A09]. Dollar values remain scenarios because the funnel steps they multiply are scenarios.", "",
     "## Totals", "",
     "| Metric | Low | Base | High |", "|---|---|---|---|"]
rows = [('TAM units', 'tam_units'), ('  of which employer (<20 paid employees)', 'tam_employer_units'), ('  of which viable solo operators', 'tam_solo_units'),
        ('SAM units', 'sam_units'), ('  of which employer', 'sam_employer_units'), ('  of which solo', 'sam_solo_units'), ('SAM as % of TAM', 'sam_pct_of_tam'),
        ('SOM accounts (36 months)', 'som_accounts'), ('SOM ARR, USD (scenario)', 'som_arr_usd'), ('SAM annual value, USD (scenario)', 'sam_annual_value_usd'), ('TAM annual value at list-price ARPA, USD (scenario)', 'tam_annual_value_usd_at_arpa')]
for label, k in rows:
    L.append(f"| {label} | " + " | ".join(f"{fmt(t[s][k])} [M:{s}.{k}]" for s in ('low', 'base', 'high')) + " |")
L += ["", "Note: TAM employer units are identical across scenarios because they are a Census count; only the solo receipts floor changes TAM. 'Low' uses the strictest floor ($50,000), 'high' the loosest ($10,000) [A01].", "",
      "## Scenario assumptions", "", "| ID | Name | Low | Base | High | Basis |", "|---|---|---|---|---|---|"]
for a in A['assumptions']:
    if 'low' in a:
        L.append(f"| [{a['id']}] | {a['name']} | {a['low']} | {a['base']} | {a['high']} | {a['basis']} |")
    elif 'tier_values' in a:
        L.append(f"| [{a['id']}] | {a['name']} | " + " | ".join(", ".join(f"{t_}:{a['tier_values'][t_][s]}" for t_ in ('P1', 'P2', 'P3')) for s in ('low', 'base', 'high')) + f" | {a['basis']} |")
    elif 'employer' in a:
        L.append(f"| [{a['id']}] | {a['name']} | " + " | ".join(f"employer {a['employer'][s]}, solo {a['solo'][s]}" for s in ('low', 'base', 'high')) + f" | {a['basis']} |")
    elif 'solo_mix' in a:
        L.append(f"| [{a['id']}] | {a['name']} | " + " | ".join(f"solo: {a['solo_mix'][s]}; employer: {a['employer_mix'][s]}" for s in ('low', 'base', 'high')) + f" | {a['basis']} |")
    else:
        L.append(f"| [{a['id']}] | {a['name']} | rule | {a['value']} | rule | {a['basis']} |")
arpa = json.load(open(P('data/derived/arpa_v1.json')))['arpa_usd_month']
L += ["", "## ARPA used (USD per paying account per month)", "",
      "Computed from Built2Bid's real list prices in `data/pricing.json` [S13]: Individual Unlimited $19.99/month [E180] or $199/year [E181]; Team $49.99/month with 3 users included [E182], users 4-5 at $19.99 [E183]. Only the plan mix is a scenario [A07].", "",
      "| Account type | Low | Base | High |", "|---|---|---|---|"]
for k, lbl in (('solo', 'Solo operator'), ('employer', 'Employer business (<20 paid employees)')):
    L.append(f"| {lbl} | " + " | ".join(f"{arpa[k][s]} [T:arpa.{k}.{s}]" for s in ('low', 'base', 'high')) + " |")
L += ["", "## Base-scenario detail by segment", "", "| Segment | Tier used | TAM units | Fit weight | SAM units | SOM accounts | SOM ARR USD (scenario) |", "|---|---|---|---|---|---|---|"]
for r in mseg:
    if r['scenario'] == 'base':
        L.append(f"| {r['segment_id']} | {r['tier_used']} | {fmt(r['tam_units'])} | {r['fit_weight']} | {fmt(r['sam_units'])} | {fmt(r['som_accounts'])} | {fmt(r['som_arr_usd'])} [T:mseg.base.{r['segment_id']}] |")
L += ["", "## Versioning", "",
      "- v1.0.0 (2026-11-23): first model. Inputs: CBP 2023, NES 2024, assumptions A01-A08, placeholder ARPA.",
      "- v1.1.0 (2026-11-23): ARPA now computed from Built2Bid's real list prices (S13); A07 rewritten as a plan-mix assumption; A09 added (free plan excluded). Unit counts unchanged.",
      "- To create a new version: copy `data/assumptions.json`, change values, bump `model_version`, run `python3 scripts/build.py && python3 scripts/render_reports.py && python3 -m pytest tests -q`. Keep prior outputs by tagging the folder or committing to the feature branch.", ""]
w('05_addressable_market_scenario_model.md', "\n".join(L))
print('rendered 02-05')

# ---------------- 06 Confidence & gaps ----------------
gaps = rd('data/gaps.csv')
L = ["# Research Confidence and Gaps Report (v1.0.0)", "",
     "Generated from `data/sources.json`, `data/evidence.csv` and `data/gaps.csv`.", "",
     "## Source verification outcome", "",
     "| ID | Requested source | Status | Confidence | Key limitation |", "|---|---|---|---|---|"]
for s in sources['sources']:
    L.append(f"| [{s['id']}] | {s['requested_name']} | {s['verification_status']} | {s['confidence']} | {s['limitations']} |")
from collections import Counter
cnt = Counter(e['confidence'] for e in evidence)
L += ["", "## Evidence rows by confidence grade", "", "| Grade | Rows |", "|---|---|"]
for g in sorted(cnt):
    L.append(f"| {g} | {cnt[g]} [PARAM: count of rows in data/evidence.csv] |")
L += ["", "## Confidence by deliverable", "",
      "| Deliverable | Confidence | Why |", "|---|---|---|",
      "| Employer audience counts (CBP <20 paid employees) | High | Official administrative data; proxy rule documented [A02] [G05] |",
      "| Solo operator counts, NAICS 23 total and electrical / plumbing-HVAC | High | Published NES size classes; receipts floor is a scenario [A01] |",
      "| Solo operator counts for other individual trades | Low-medium | Allocated from 4-digit NES groups [A03] [G02] |",
      "| Trade Priority Matrix | Medium (size, authority) / Low (judgment dimensions) | Five of seven dimensions are analyst judgment [G07] [G09] |",
      "| Personas | Medium-low | Evidence-informed composites, not interview-validated [G08] |",
      "| TAM (units) | Medium-high | Census-derived with documented rules |",
      "| SAM / SOM | Low | Driven by scenario assumptions without representative data [A04] [A05] [A06] [G03] |",
      "| Any dollar value | Low (scenario) | Real list prices [S13] but assumed plan mix [A07] and scenario funnel [G01] |",
      "", "## Gaps and resolution plan", "", "| ID | Area | Gap | Impact | Severity | Proposed resolution | When |", "|---|---|---|---|---|---|---|"]
for g in gaps:
    L.append(f"| [{g['id']}] | {g['area']} | {g['gap']} | {g['impact']} | {g['severity']} | {g['proposed_resolution']} | {g['phase']} |")
L += ["", "## What was deliberately not done", "",
      "- No lead forms were submitted (for example, the RoofersCoffeeShop full report) because that shares contact details with a third party [G11].",
      "- No Census API key was requested (creating an access key needs the owner's approval). Bulk public files gave the same data.",
      "- No paid data sources were licensed or purchased.", ""]
w('06_research_confidence_and_gaps.md', "\n".join(L))
print('rendered 06')
