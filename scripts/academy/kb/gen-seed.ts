/**
 * Generates supabase/migrations/20270220002000_academy_knowledge_seed.sql from
 *   src/lib/academy/kb/seed/catalog.ts            (families, sources, adoptions, terms, summaries)
 *   src/lib/academy/kb/seed/official-snapshot.json (official text: python3 -I scripts/academy/kb/fetch_official.py)
 * Run: npx tsx scripts/academy/kb/gen-seed.ts
 *
 * Idempotent and non-destructive: deterministic ids (md5 of a stable key) + ON CONFLICT DO NOTHING, so re-running never
 * overwrites what an Academy admin changed. "verified" rows are inserted together with their verification record
 * (method official_text, the official URL, quoted evidence and the SHA-256 of the fetched text).
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ADOPTIONS, FAMILIES, IRC_TITLES, JURISDICTIONS, MN_AMENDS, SUMMARIES, TERMS, sourceSeeds } from "../../../src/lib/academy/kb/seed/catalog";

const ROOT = path.resolve(import.meta.dirname, "../../..");
type Snap = {
  fetched_at: string; ecfr_dates: Record<string, string>;
  ecfr: { title: number; part: string; section: string; head: string; url: string; as_of: string; read_url: string; trades: string[]; topics: string[]; section_hash: string; rows: { paragraph: string | null; text: string; hash: string }[] }[];
  state_plans: { section: string; state: string; head: string; url: string; as_of: string; read_url: string; evidence: string; hash: string }[];
  mn: { part: string; url: string; heading: string; history: string; hash: string; trades: string[]; topics: string[]; subparts: { subp: string | null; title: string; text: string }[] }[];
  evidence: { key: string; url: string; quotes: string[]; missing: string[] }[];
};
const snap = JSON.parse(readFileSync(path.join(ROOT, "src/lib/academy/kb/seed/official-snapshot.json"), "utf8")) as Snap;

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs: string[] | undefined) => (xs && xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const id = (key: string) => `md5(${q(`academykb:${key}`)})::uuid`;
const sha = (s: string) => createHash("sha256").update(s.replace(/\s+/g, " ").trim()).digest("hex");
const at = q(snap.fetched_at);

const out: string[] = [];
const verifs: string[] = [];
const verify = (type: string, key: string, url: string, evidence: string, hash: string | null, notes?: string) =>
  verifs.push(`  (${q(type)}, (${id(key)})::text, ${at}::timestamptz, 'official_text', 'verified', ${q(url)}, ${q(hash)}, ${q(evidence.slice(0, 4000))}, ${q(notes ?? null)})`);

out.push(`-- Generated by scripts/academy/kb/gen-seed.ts. Do not edit by hand.
-- Official text fetched ${snap.fetched_at} (eCFR current as of ${Object.values(snap.ecfr_dates).join(" / ")}; Minnesota Revisor; MN DLI).
-- Safe to re-run: deterministic ids + ON CONFLICT DO NOTHING. Verified rows carry a verification record with evidence.
-- Requires 20270220001000_academy_knowledge.sql.

select set_config('academy.kb_verifying', 'on', false);
`);

// Jurisdictions
out.push("insert into public.academy_kb_jurisdictions (id, level, state_code, parent_id, name, coverage, sort_order) values");
out.push(JURISDICTIONS.map((j) => `  (${q(j.id)}, ${q(j.level)}, ${q(j.state)}, ${j.id === "US" ? "null" : "'US'"}, ${q(j.name)}, ${q(j.id === "MN" || j.id === "US" ? "partial" : "awaiting_verification")}, ${j.sort})`).join(",\n") + "\non conflict (id) do nothing;\n");

// Families
out.push("insert into public.academy_kb_families (slug, name, short_name, kind, publisher, about, sort_order) values");
out.push(FAMILIES.map((f) => `  (${[f.slug, f.name, f.short, f.kind, f.publisher, f.about, f.sort].map(q).join(", ")})`).join(",\n") + "\non conflict (slug) do nothing;\n");

// Evidence lookups
const mnByPart = new Map(snap.mn.map((m) => [m.part, m]));
const ecfrBySection = new Map(snap.ecfr.map((e) => [e.section, e]));
const dli = new Map(snap.evidence.map((e) => [e.key, e]));
for (const e of snap.evidence) if (e.missing.length) throw new Error(`Evidence quote missing on ${e.url}: ${e.missing.join(" | ")}`);
const firstSubpart = (part: string) => {
  const m = mnByPart.get(part);
  if (!m) throw new Error(`No snapshot for Minn. R. ${part}`);
  return { url: m.url, text: m.subparts[0]?.text ?? "", hash: m.hash };
};
const evidenceFor = (from: string): { url: string; text: string; hash: string | null } => {
  const i = from.indexOf(":");
  const [kind, key] = [from.slice(0, i), from.slice(i + 1)];
  if (kind === "mn") return firstSubpart(key);
  if (kind === "dli") { const e = dli.get(key)!; return { url: e.url, text: e.quotes.map((x) => `"${x}"`).join(" … "), hash: null }; }
  if (kind === "ecfr") { const e = ecfrBySection.get(key)!; return { url: e.read_url, text: `${e.head} ${e.rows[0].text.slice(0, 500)}`, hash: e.section_hash }; }
  throw new Error(`Unknown evidence ${from}`);
};

// Sources
const sources = sourceSeeds(snap.ecfr_dates);
const modelEvidence: Record<string, string> = { "irc-2018": "mn:1309.0010", "ibc-2018": "mn:1305.0011", "imc-2018": "mn:1346.0050", "iecc-2012": "mn:1322.0010", "nec-2026": "mn:1315.0200", "nec-2023": "dli:mn-dli-electrical" };
const sourceEvidence: Record<string, string> = { "osha-1926": "ecfr:1926.20", "osha-1904": "ecfr:1904.1", "epa-745": "ecfr:745.82", fmcsa: "ecfr:391.11",
  "mn-1300": "mn:1300.0120", "mn-1305": "mn:1305.0011", "mn-1309": "mn:1309.0010", "mn-1315": "mn:1315.0200", "mn-1322": "mn:1322.0010", "mn-1346": "mn:1346.0050", ...modelEvidence };
out.push("insert into public.academy_kb_sources (id, family_slug, title, short_title, edition, edition_year, publisher, jurisdiction_id, official_url, read_url, rights, fulltext_allowed, excerpt_allowed, rights_note, pagination_note, status, check_url, last_verified_at, last_checked_at) values");
out.push(sources.map((s) => `  (${[id(`source:${s.key}`), q(s.family), q(s.title), q(s.short), q(s.edition), q(s.year), q(s.publisher), q(s.jurisdiction), q(s.officialUrl), q(s.readUrl), q(s.rights),
  q(s.fulltext), q(s.excerpt), q(s.rightsNote), q(s.paginationNote ?? null), q(s.status), q(s.checkUrl ?? s.officialUrl), s.status === "verified" ? `${at}::timestamptz` : "null", `${at}::timestamptz`].join(", ")})`).join(",\n") + "\non conflict do nothing;\n");
for (const s of sources) {
  if (s.status !== "verified") continue;
  if (s.key === "osha-1952") { const p = snap.state_plans[0]; verify("source", `source:${s.key}`, p.read_url, `${p.head} ${p.evidence.slice(0, 400)}`, p.hash); continue; }
  const ev = evidenceFor(sourceEvidence[s.key] ?? (() => { throw new Error(`No evidence for source ${s.key}`); })());
  verify("source", `source:${s.key}`, ev.url, ev.text, ev.hash, modelEvidence[s.key] ? "Edition confirmed by the adopting jurisdiction's official text." : undefined);
}

// Adoptions (+ OSHA State Plans from 29 CFR 1952 subpart A)
const adoptRows: string[] = [];
for (const a of ADOPTIONS) {
  adoptRows.push(`  (${[id(`adoption:${a.key}`), q(a.jurisdiction), id(`source:${a.source}`), q(a.kind), q(a.replacesFamily ?? null), q(a.scope ?? null), q(a.authority), q(a.url),
    a.effective ? `${q(a.effective)}::date` : "null", a.expires ? `${q(a.expires)}::date` : "null", q(a.localConfirmation), arr(a.trades), q(a.status), a.status === "verified" ? `${at}::timestamptz` : "null"].join(", ")})`);
  if (a.status === "verified") { const ev = evidenceFor(a.evidenceFrom); verify("adoption", `adoption:${a.key}`, ev.url, ev.text, ev.hash); }
}
for (const p of snap.state_plans) {
  for (const fam of ["osha_construction", "osha_recordkeeping"]) {
    const key = `adoption:stateplan:${p.state}:${fam}`;
    adoptRows.push(`  (${[id(key), q(p.state), id("source:osha-1952"), q("replaces"), q(fam), q(`${p.head.replace(/^§\s*/, "")} OSHA-approved State Plan covering private-sector and state and local government employers. The state's standards and enforcement govern and must be at least as effective as the federal rules.`),
      q(`29 CFR ${p.section}`), q(p.read_url), "null", "null", "true", "'{}'::text[]", "'verified'", `${at}::timestamptz`].join(", ")})`);
    verify("adoption", key, p.read_url, `${p.head} ${p.evidence.slice(0, 500)}`, p.hash, "Listed in 29 CFR 1952 subpart A (approved State Plans for private-sector and state and local government employees).");
  }
}
out.push("insert into public.academy_kb_adoptions (id, jurisdiction_id, source_id, kind, replaces_family, scope_note, authority_citation, official_url, effective_date, expiration_date, local_confirmation_required, trades, status, last_verified_at) values");
out.push(adoptRows.join(",\n") + "\non conflict do nothing;\n");

// Sections
const secRows: string[] = [];
const sectionCols = "id, source_id, section_number, citation, title, heading_path, kind, body_kind, body, summary, page, amends_source_id, amends_section, amend_action, trades, topics, effective_date, official_url, status, last_verified_at, content_hash, sort_order";
const sec = (key: string, v: { source: string; number: string; citation: string; title: string; heading?: string | null; kind: string; bodyKind: string; body: string | null; summary?: string | null;
  amendsSource?: string | null; amendsSection?: string | null; amendAction?: string | null; trades: string[]; topics: string[]; effective?: string | null; url: string | null; status: string; hash?: string | null; sort: number }) => {
  secRows.push(`  (${[id(key), id(`source:${v.source}`), q(v.number), q(v.citation), q(v.title.slice(0, 300)), q(v.heading ?? null), q(v.kind), q(v.bodyKind), q(v.body), q(v.summary ?? null), "null",
    v.amendsSource ? id(`source:${v.amendsSource}`) : "null", q(v.amendsSection ?? null), q(v.amendAction ?? null), arr(v.trades), arr(v.topics), v.effective ? `${q(v.effective)}::date` : "null",
    q(v.url), q(v.status), v.status === "verified" ? `${at}::timestamptz` : "null", q(v.hash ?? null), v.sort].join(", ")})`);
};

const sourceForCfr = (title: number, part: string) => (title === 29 ? (part === "1904" ? "osha-1904" : "osha-1926") : title === 40 ? "epa-745" : "fmcsa");
let sort = 0;
for (const e of snap.ecfr) {
  const sectionTitle = e.head.replace(/^§\s*[\d.]+[A-Z]?\s*/, "").replace(/\.$/, "");
  for (const r of e.rows) {
    const number = r.paragraph ? `${e.section}(${r.paragraph})` : e.section;
    const own = r.paragraph ? new RegExp(`^\\(${r.paragraph}\\)\\s+([A-Z][^.—]{2,90})[.—]`).exec(r.text)?.[1] : null;
    const title = r.paragraph ? `${sectionTitle}: ${own ? own : `paragraph (${r.paragraph})`}` : sectionTitle;
    const key = `section:cfr:${number}`;
    sec(key, { source: sourceForCfr(e.title, e.part), number, citation: `${e.title} CFR ${number}`, title, heading: `${e.title} CFR Part ${e.part} › § ${e.section} ${sectionTitle}`, kind: "requirement", bodyKind: "full_text",
      body: r.text, summary: SUMMARIES[number] ?? null, trades: e.trades, topics: e.topics, url: r.paragraph ? `${e.read_url}#p-${e.section}(${r.paragraph})` : e.read_url, status: "verified", hash: r.hash, sort: sort++ });
    verify("section", key, e.read_url, r.text.slice(0, 600), r.hash, `eCFR versioner API, title ${e.title} current as of ${e.as_of}.`);
  }
}
for (const p of snap.state_plans) {
  const key = `section:cfr:${p.section}`;
  sec(key, { source: "osha-1952", number: p.section, citation: `29 CFR ${p.section}`, title: `Approved State Plan: ${p.head.replace(/^§\s*[\d.]+\s*/, "").replace(/\.$/, "")}`, heading: "29 CFR Part 1952 › Subpart A", kind: "scope", bodyKind: "full_text",
    body: p.evidence, summary: `${p.head.replace(/^§\s*[\d.]+\s*/, "").replace(/\.$/, "")} runs an OSHA-approved State Plan for private-sector employers. Its own safety standards and enforcement apply there.`, trades: [], topics: ["osha state plan", "state plan"], url: p.read_url, status: "verified", hash: p.hash, sort: sort++ });
  verify("section", key, p.read_url, p.evidence.slice(0, 600), p.hash);
}

const MN_EFFECTIVE: Record<string, string> = { "1300": "2020-03-31", "1305": "2020-03-31", "1309": "2020-03-31", "1346": "2020-04-06", "1315": "2026-08-17" };
const titleCase = (s: string) => s.toLowerCase().replace(/\b([a-z])/g, (m) => m.toUpperCase()).replace(/\b(Of|And|By|The|For|To|In)\b/g, (m) => m.toLowerCase()).replace(/\bIrc\b/g, "IRC").replace(/\bIbc\b/g, "IBC").replace(/\bIecc\b/g, "IECC").replace(/\bR(\d)/g, "R$1");
for (const m of snap.mn) {
  const chapter = m.part.split(".")[0];
  const amendsSource = MN_AMENDS[chapter] ?? null;
  const heading = titleCase(m.heading);
  for (const sp of m.subparts) {
    if (/^Subp(?:art|\.)\s*\d+[a-z]?\.\s*\[Repealed/.test(sp.text) || sp.text.length < 60) continue;
    const n = /^Subp(?:art|\.)\s*(\d+[a-z]?)\./.exec(sp.text)?.[1] ?? null;
    const number = n ? `${m.part} subp. ${n}` : m.part;
    const subTitle = n ? (/^Subp(?:art|\.)\s*\d+[a-z]?\.\s*(.*?)\.\s/.exec(sp.text)?.[1] ?? "") : "";
    const probe = `${subTitle} ${sp.text.slice(0, 260)}`;
    const amendsSection = amendsSource ? (/(?:IRC|IBC|IECC|IMC)?\s*(?:[Ss]ection|Table)\s+((?:R|N|E|M|P)?\d{2,4}(?:\.\d+)*(?:\(\d+\))?)/.exec(probe)?.[1] ?? null) : null;
    const action = !amendsSection ? null : /deleted and replaced|is replaced/.test(probe) ? "replaced" : /deleted in its entirety|is deleted/.test(probe) ? "deleted" : /is added|are added/.test(probe) ? "added" : "amended";
    const summaryKey = `mn:${m.part}:${n ?? "1"}`;
    const kind = amendsSection ? "amendment" : /0010|0011|0050|0200/.test(m.part) ? "scope" : "administrative";
    const key = `section:mn:${number}`;
    sec(key, { source: `mn-${chapter}`, number, citation: n ? `Minn. R. ${m.part}, subp. ${n}` : `Minn. R. ${m.part}`, title: subTitle && subTitle.toLowerCase() !== m.heading.toLowerCase() ? `${heading}: ${subTitle}` : heading,
      heading: `Minnesota Rules › Chapter ${chapter} › ${m.part} ${heading}`, kind, bodyKind: "excerpt", body: sp.text, summary: SUMMARIES[summaryKey] ?? null, amendsSource: amendsSection ? amendsSource : null,
      amendsSection: amendsSection && !amendsSection.match(/^[RNEMP]/) && amendsSource === "irc-2018" ? `R${amendsSection}` : amendsSection, amendAction: action, trades: m.trades, topics: m.topics,
      effective: MN_EFFECTIVE[chapter] ?? null, url: m.url, status: "verified", hash: sha(sp.text), sort: sort++ });
    verify("section", key, m.url, sp.text.slice(0, 600), sha(sp.text), m.history ? `Revisor history: ${m.history}` : undefined);
  }
}
for (const t of IRC_TITLES) {
  sec(`section:irc2018:${t.section}`, { source: "irc-2018", number: t.section, citation: `2018 IRC Section ${t.section}`, title: t.title, heading: "2018 International Residential Code", kind: "title_only", bodyKind: "title_only",
    body: null, summary: null, trades: t.trades, topics: t.topics, url: null, status: "pending_review", sort: sort++ });
}
out.push(`insert into public.academy_kb_sections (${sectionCols}) values`);
out.push(secRows.join(",\n") + "\non conflict do nothing;\n");

// Terms
out.push("insert into public.academy_kb_terms (term, synonyms, topics, related, trades, note) values");
out.push(TERMS.map((t) => `  (${[q(t.term), arr(t.synonyms), arr(t.topics), arr(t.related), arr(t.trades ?? []), q(t.note ?? null)].join(", ")})`).join(",\n") + "\non conflict (term) do nothing;\n");

// Verification records (only for rows this script inserted for the first time: skip when a record for the target exists).
out.push("insert into public.academy_kb_verifications (target_type, target_id, checked_at, method, result, source_url, content_hash, evidence, notes)");
out.push("select v.* from (values");
out.push(verifs.join(",\n"));
out.push(") as v(target_type, target_id, checked_at, method, result, source_url, content_hash, evidence, notes)\nwhere not exists (select 1 from public.academy_kb_verifications x where x.target_type = v.target_type and x.target_id = v.target_id);\n");

out.push("select set_config('academy.kb_verifying', 'off', false);\n");
const file = path.join(ROOT, "supabase/migrations/20270220002000_academy_knowledge_seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`wrote ${file}: ${sources.length} sources, ${adoptRows.length} adoptions, ${secRows.length} sections, ${TERMS.length} terms, ${verifs.length} verification records`);
