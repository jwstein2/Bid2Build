#!/usr/bin/env python3
"""
Generates supabase/migrations/20270222002000_academy_kb_local_seed.sql from the Minnesota DLI jurisdiction directory
snapshot (src/lib/academy/kb/seed/mn-jurisdictions.json, fetched by fetch_mn_jurisdictions.py) and the Census-based
picker ids (public/academy-geo, built by gen_geo.py), so a city/township picked by ZIP maps to its DLI record.
  python3 scripts/academy/kb/gen_local_seed.py
"""
import glob, json, re

SNAP = json.load(open("src/lib/academy/kb/seed/mn-jurisdictions.json"))
DUPS = set(json.load(open("src/lib/academy/kb/seed/place-dups.json")))
OUT = "supabase/migrations/20270222002000_academy_kb_local_seed.sql"
SRC = "https://workplace.doli.state.mn.us/jurisdiction/"


def slug(s):
    s = re.sub(r"\bste\.?\s", "sainte ", re.sub(r"\bst\.?\s", "saint ", s.lower() + " ")).replace("&", " and ")
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", s)).strip("-")[:60]


def q(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def title(s):
    t = " ".join(w.capitalize() for w in s.lower().split())
    return re.sub(r"\bSt\b", "St.", re.sub(r"\bMc(\w)", lambda m: "Mc" + m.group(1).upper(), t))


labels = {}
for f in glob.glob("public/academy-geo/*.json"):
    for z, opts in json.load(open(f)).items():
        for o in opts:
            if o[0].startswith("MN:"):
                labels[o[0]] = o[1]

counties, rows, seen = {}, [], set()
for r in SNAP["records"]:
    cs = slug(r["county"])
    cid = f"MN:{cs}-county"
    counties[cid] = f"{title(r['county'])} County"
    if r["city"]:
        base = slug(r["city"])
        jid = f"MN:{base}-{cs}" if f"MN:{base}" in DUPS else f"MN:{base}"
        name, kind = labels.get(jid, title(r["city"])), "city"
    else:
        t = r["township"]
        unorg = bool(re.match(r"^T\d+", t)) or t.upper().startswith("UNORG")
        jid = f"MN:{cs}:{slug(t)}-twp"
        name = labels.get(jid, f"{t.upper() if unorg else title(t)} {'(unorganized territory)' if unorg else 'Township'}, {title(r['county'])} County")
        kind = "unorganized" if unorg else "township"
    if jid in seen:
        continue
    seen.add(jid)
    status = {"YES": "enforces", "NO": "not_enforced"}.get(r["adopted"], "unknown")
    phone = r["bo_phone"] if r["bo_phone"] and re.match(r"^\(\d{3}\) \d{3}-\d{4}$", r["bo_phone"]) else None
    detail = {k: v for k, v in {
        "electrical": (r["electrical"] or "").lower() or None,
        "accessibility": (r["accessibility"] or "").lower() or None,
        "opt_1306_2": r["opt_1306_2"] == "YES" if r["opt_1306_2"] else None,
        "opt_1306_3": r["opt_1306_3"] == "YES" if r["opt_1306_3"] else None,
        "plumbing_inspects": r["plumbing_inspects"] == "YES" if r["plumbing_inspects"] else None,
    }.items() if v is not None}
    short = name.split(", ")[0] if kind != "city" else name
    b = lambda v: "" if v is None else ("1" if v else "0")
    rows.append("|".join([jid[3:], short.replace("|", "/"), kind[0], cs, {"enforces": "Y", "not_enforced": "N"}.get(status, "U"), phone or "",
                          (detail.get("electrical") or "")[:1], (detail.get("accessibility") or "")[:1], b(detail.get("opt_1306_2")),
                          b(detail.get("opt_1306_3")), b(detail.get("plumbing_inspects"))]))

at = SNAP["fetched_at"]
out = [
    "-- Generated by scripts/academy/kb/gen_local_seed.py. Do not edit by hand.",
    f"-- Minnesota local permitting authorities from the DLI State Building Code jurisdiction directory ({SRC}), fetched {at}.",
    "-- Safe to re-run (on conflict do nothing). Requires 20270222001000_academy_kb_local.sql.",
    "",
    "insert into public.academy_kb_jurisdictions (id, level, state_code, parent_id, name, coverage, kind, county_name, local_status, source_url, verified_at) values",
    ",\n".join(f"  ({q(c)}, 'county', 'MN', 'MN', {q(n)}, 'awaiting_verification', 'county', {q(n)}, 'unknown', null, null)" for c, n in sorted(counties.items())),
    "on conflict (id) do nothing;",
    "",
    "-- Local authorities, loaded in chunks through academy_kb_load_local() (one compact line per authority).",
] + [f"select public.academy_kb_load_local('MN', {q(SRC)}, {q(at)}::timestamptz, {q(chr(10).join(rows[i:i + 600]))});\n" for i in range(0, len(rows), 600)] + [
    "insert into public.academy_kb_verifications (target_type, target_id, checked_at, method, result, source_url, evidence, notes) values",
    f"  ('jurisdiction', 'MN', {q(at)}::timestamptz, 'official_text', 'verified', 'https://workplace.doli.state.mn.us/jurisdiction/', "
    + q(f"DLI State Building Code jurisdiction directory: {len(rows)} Minnesota cities, townships and unorganized territories with 'HAS ADOPTED THE BUILDING CODE' (YES/NO), optional 1306 subparts, electrical authority and building official phone, fetched county by county.")
    + ", 'Local records are verified only for what the directory states. Inspector names are not stored.')",
    "on conflict do nothing;",
    "",
]
open(OUT, "w").write("\n".join(out))
print(f"wrote {OUT}: {len(counties)} counties, {len(rows)} local authorities")
