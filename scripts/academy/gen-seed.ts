/**
 * Generates supabase/migrations/20261230002000_academy_content_seed.sql from the content catalog
 * (src/lib/academy/content). Run: npx tsx scripts/academy/gen-seed.ts
 *
 * Idempotent and non-destructive: every row has a deterministic id (md5 of a stable key) and is inserted with
 * ON CONFLICT DO NOTHING, so re-running never overwrites edits an Academy admin made in /academy/manage.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { ACADEMY_TRADES, ALL_COURSES, courseCover } from "../../src/lib/academy/content/catalog";
import { RESOURCES } from "../../src/lib/academy/content/resources";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs: string[] | undefined) => (xs && xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (v: unknown) => (v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const id = (key: string) => `md5(${q(`academy:${key}`)})::uuid`;

const out: string[] = [];
out.push(`-- Generated by scripts/academy/gen-seed.ts. Do not edit by hand; edit src/lib/academy/content and regenerate.
-- Seeds the Contractor Academy trades, verified resources, the Contractor Sales Academy and ${ALL_COURSES.length - 1} trade course cards.
-- Safe to re-run: deterministic ids + ON CONFLICT DO NOTHING (admin edits are never overwritten).
`);

out.push("insert into public.academy_trades (slug, name, family, icon, intro, seo_title, seo_description, sales_challenge, sort_order) values");
out.push(ACADEMY_TRADES.map((t) => `  (${[t.slug, t.name, t.family, t.icon, t.intro, t.seoTitle, t.seoDescription, t.salesChallenge, t.sort].map(q).join(", ")})`).join(",\n") + "\non conflict (slug) do nothing;\n");

out.push("insert into public.academy_resources (id, kind, title, creator_name, creator_url, community_name, platform, source_url, embed_id, embed_allowed, thumbnail_url, summary, why_it_matters, takeaways, trades, skill, access_note, permission_status, views_at_verification, verified_at, verification_note, status) values");
out.push(RESOURCES.map((r) => `  (${[
  id(`resource:${r.key}`), q(r.kind), q(r.title), q(r.creatorName), q(r.creatorUrl), q(r.communityName), q(r.platform), q(r.sourceUrl), q(r.embedId),
  q(r.embedAllowed), q(r.embedId && r.embedAllowed ? `https://i.ytimg.com/vi/${r.embedId}/hqdefault.jpg` : null), q(r.summary), q(r.whyItMatters),
  arr(r.takeaways), arr(r.trades), q(r.skill), q(r.accessNote), q(r.permission), q(r.viewsAtVerification ?? null), `${q(r.verifiedAt)}::date`, q(r.verificationNote), "'verified'",
].join(", ")})`).join(",\n") + "\non conflict do nothing;\n");

const courseRows: string[] = [];
const moduleRows: string[] = [];
const lessonRows: string[] = [];
const lessonRes: string[] = [];
const courseRes: string[] = [];
for (const c of ALL_COURSES) {
  courseRows.push(`  (${[
    id(`course:${c.slug}`), q(c.slug), q(c.trade), q(c.pillar), q(c.title), q(c.summary), q(c.description), q(c.level), q(c.access), q(c.status),
    q(c.contentClass), q(courseCover(c.pillar)), q(Boolean(c.featured)), q(c.sort), arr(c.plannedLessons), q(c.seoTitle ?? null), q(c.seoDescription ?? null),
    c.status === "published" ? "now()" : "null",
  ].join(", ")})`);
  (c.resources ?? []).forEach((k, i) => courseRes.push(`  (${id(`course:${c.slug}`)}, ${id(`resource:${k}`)}, ${i})`));
  const modules = [...new Set((c.lessons ?? []).map((l) => l.module))];
  modules.forEach((m, i) => moduleRows.push(`  (${id(`module:${c.slug}:${m}`)}, ${id(`course:${c.slug}`)}, ${q(m)}, ${i})`));
  (c.lessons ?? []).forEach((l, i) => {
    lessonRows.push(`  (${[
      id(`lesson:${c.slug}:${l.slug}`), id(`course:${c.slug}`), id(`module:${c.slug}:${l.module}`), q(l.slug), q(l.title), q(l.summary), q(l.body),
      arr(l.takeaways), arr(l.checklist), json(l.tradeNotes ?? {}), json(l.action ?? null), json(l.quiz ?? null), q(l.access), "'published'", q(l.minutes), q(i * 10),
    ].join(", ")})`);
    (l.resources ?? []).forEach((r, j) => lessonRes.push(`  (${id(`lesson:${c.slug}:${l.slug}`)}, ${id(`resource:${r.key}`)}, ${j}, ${q(r.note)})`));
  });
}
out.push("insert into public.academy_courses (id, slug, trade_slug, pillar, title, summary, description, level, access, status, content_class, cover_theme, featured, sort_order, planned_lessons, seo_title, seo_description, published_at) values");
out.push(courseRows.join(",\n") + "\non conflict do nothing;\n");
out.push("insert into public.academy_modules (id, course_id, title, sort_order) values");
out.push(moduleRows.join(",\n") + "\non conflict do nothing;\n");
out.push("insert into public.academy_lessons (id, course_id, module_id, slug, title, summary, body_md, takeaways, checklist, trade_notes, app_action, quiz, access, status, estimated_minutes, sort_order) values");
out.push(lessonRows.join(",\n") + "\non conflict do nothing;\n");
out.push("insert into public.academy_lesson_resources (lesson_id, resource_id, sort_order, note) values");
out.push(lessonRes.join(",\n") + "\non conflict do nothing;\n");
out.push("insert into public.academy_course_resources (course_id, resource_id, sort_order) values");
out.push(courseRes.join(",\n") + "\non conflict do nothing;\n");

const file = path.resolve(import.meta.dirname, "../../supabase/migrations/20261230002000_academy_content_seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`wrote ${file}: ${ACADEMY_TRADES.length} trades, ${RESOURCES.length} resources, ${ALL_COURSES.length} courses, ${lessonRows.length} lessons`);
