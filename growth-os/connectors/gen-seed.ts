// Generates the SQL seed for growth.connectors / growth.connector_operations from registry.ts.
// Usage: npx tsx growth-os/connectors/gen-seed.ts   (writes the seed migration; tests check it is in sync)
import { writeFileSync } from "node:fs";
import path from "node:path";
import { CONNECTORS } from "./registry";

export const SEED_PATH = path.resolve(import.meta.dirname, "../supabase/migrations/20270302001100_growth_connectors_seed.sql");

const lit = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => (a.length ? `array[${a.map(lit).join(", ")}]::text[]` : "'{}'::text[]");

export function seedSql(): string {
  const out: string[] = [
    "-- GENERATED by growth-os/connectors/gen-seed.ts from growth-os/connectors/registry.ts. Do not edit by hand.",
    "-- Idempotent: upserts the registry; never touches growth.connections. STAGING / TEST ONLY until production is approved.",
    "",
  ];
  CONNECTORS.forEach((c, i) => {
    out.push(`insert into growth.connectors (provider, name, grp, auth_kinds, baseline_status, baseline_reason, existing, review, limits, cost, refresh, docs, manual_steps, manual_secrets, sort)
values (${lit(c.provider)}, ${lit(c.name)}, ${lit(c.group)}, ${arr(c.authKinds)}, ${lit(c.baseline)}, ${lit(c.baselineReason)}, ${lit(c.existing)}, ${lit(c.review)}, ${lit(c.limits)}, ${lit(c.cost)}, ${lit(c.refresh)}, ${arr(c.docs)}, ${arr(c.manualSteps)}, ${arr((c.manualSecrets ?? []).map((m) => m.name))}, ${i})
on conflict (provider) do update set name = excluded.name, grp = excluded.grp, auth_kinds = excluded.auth_kinds, baseline_status = excluded.baseline_status,
  baseline_reason = excluded.baseline_reason, existing = excluded.existing, review = excluded.review, limits = excluded.limits, cost = excluded.cost,
  refresh = excluded.refresh, docs = excluded.docs, manual_steps = excluded.manual_steps, manual_secrets = excluded.manual_secrets, sort = excluded.sort, updated_at = now();`);
    out.push(`delete from growth.connector_operations where provider = ${lit(c.provider)} and op_key <> all (${arr(c.operations.map((o) => o.key))});`);
    c.operations.forEach((o, j) => {
      out.push(`insert into growth.connector_operations (provider, op_key, label, scopes, privileged, phase, baseline_status, note, sort)
values (${lit(c.provider)}, ${lit(o.key)}, ${lit(o.label)}, ${arr(o.scopes)}, ${o.privileged}, ${o.phase}, ${lit(o.baseline)}, ${lit(o.note)}, ${j})
on conflict (provider, op_key) do update set label = excluded.label, scopes = excluded.scopes, privileged = excluded.privileged, phase = excluded.phase,
  baseline_status = excluded.baseline_status, note = excluded.note, sort = excluded.sort;`);
    });
    out.push("");
  });
  out.push(`delete from growth.connectors where provider <> all (${arr(CONNECTORS.map((c) => c.provider))}) and not exists (select 1 from growth.connections x where x.provider = growth.connectors.provider);`);
  return out.join("\n") + "\n";
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  writeFileSync(SEED_PATH, seedSql());
  console.log(`wrote ${SEED_PATH}`);
}
